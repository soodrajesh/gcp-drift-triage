"""Cross-provider evaluation on the sample drift plans.

    GOOGLE_CLOUD_PROJECT=<proj> .venv/bin/python evals/run.py --providers mock,vertex,openai

Invariants (must hold on every run):
  decisions_stable  every drift's decision and severity equal the rules-only run
  evidence_intact   attribution (actor, events) equals the rules-only run
Reported: notes kept/rejected, PR text accepted/rejected, degraded runs, cost, latency."""

import argparse
import asyncio
import json
import os
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
for line in (ROOT / ".env").read_text().splitlines() if (ROOT / ".env").exists() else []:
    k, _, v = line.partition("=")
    if k and not k.startswith("#") and k != "DRIFTRIAGE_LLM":
        os.environ.setdefault(k, v)

from driftriage.forensics import audit_from_doc  # noqa: E402
from driftriage.llm import Budget, make_llm  # noqa: E402
from driftriage.orchestrator import triage  # noqa: E402

SAMPLES = ROOT / "driftriage" / "samples"


def view(r):
    return [
        (d.address, d.decision, d.severity, d.evidence.actor, len(d.evidence.events))
        for d in r.drifts
    ]


async def main(providers, repeat, out):
    rows = []
    for name in sorted(p.stem for p in SAMPLES.glob("*.json")):
        doc = json.loads((SAMPLES / f"{name}.json").read_text())
        base = await triage(doc, make_llm("none"), audit_from_doc(doc))
        for prov in providers:
            for _ in range(repeat):
                r = await triage(doc, make_llm(prov), audit_from_doc(doc), budget=Budget())
                rows.append(
                    {
                        "plan": name,
                        "provider": f"{r.provider}/{r.model}",
                        "posture": r.posture,
                        "stable": view(r) == view(base) and r.posture == base.posture,
                        "notes": sum(1 for d in r.drifts if d.note),
                        "notes_rejected": sum(x["agent"] == "analyst" for x in r.dropped),
                        "pr_ok": bool(r.pr_text),
                        "pr_rejected": sum(x["agent"] == "drafter" for x in r.dropped),
                        "degraded": len(r.degraded),
                        "cost": r.cost_usd,
                        "ms": r.duration_ms,
                    }
                )
                print(name, rows[-1]["provider"], r.posture, flush=True)
    bad = sum(not r["stable"] for r in rows)
    c = lambda b: "✓" if b else "✗"  # noqa: E731
    L = [
        "# Evaluation results",
        "",
        "Generated by `evals/run.py`. Decisions, severities and attribution must equal the rules-only run on every run.",
        "",
        "| plan | provider | posture | stable | notes kept/rejected | PR text ok/rejected | degraded | cost | ms |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        L.append(
            f"| {r['plan']} | {r['provider']} | {r['posture']} | {c(r['stable'])} | {r['notes']}/{r['notes_rejected']} | "
            f"{c(r['pr_ok'])}/{r['pr_rejected']} | {r['degraded']} | ${r['cost']:.4f} | {r['ms']} |"
        )
    by = {}
    for r in rows:
        by.setdefault(r["provider"], []).append(r)
    L += [
        "",
        "## Per provider",
        "",
        "| provider | runs | invariant violations | notes kept | notes rejected | PR texts rejected | cost | median ms |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for p, rs in by.items():
        L.append(
            f"| {p} | {len(rs)} | {sum(not x['stable'] for x in rs)} | {sum(x['notes'] for x in rs)} | {sum(x['notes_rejected'] for x in rs)} | "
            f"{sum(x['pr_rejected'] for x in rs)} | ${sum(x['cost'] for x in rs):.4f} | {int(statistics.median(x['ms'] for x in rs))} |"
        )
    out.write_text("\n".join(L) + "\n")
    print(f"\nwrote {out}; invariant violations: {bad}")
    return 1 if bad else 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--providers", default="mock")
    ap.add_argument("--repeat", type=int, default=1)
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "eval-results.md")
    a = ap.parse_args()
    sys.exit(asyncio.run(main(a.providers.split(","), a.repeat, a.out)))
